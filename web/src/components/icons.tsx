export function Icon({
  name,
  variant = "default",
  ...props
}: {
  name: IconName;
  variant?: IconVariant;
} & SVGProps<SVGSVGElement>) {
  const navigationSymbol =
    variant === "default"
      ? undefined
      : navigationSymbols[name]?.[
          variant === "navigation-active" ? "active" : "idle"
        ];
  const filled = navigationSymbol !== undefined || filledIcons.has(name);
  const artwork = navigationSymbol ? (
    <use href={`${iconSprite}#${navigationSymbol}`} />
  ) : (
    paths[name]
  );
  return (
    <svg
      aria-hidden="true"
      data-icon={name}
      fill={filled ? "currentColor" : "none"}
      height="24"
      viewBox={iconViewBoxes[name] ?? "0 0 24 24"}
      width="24"
      {...props}
    >
      {filled ? (
        artwork
      ) : (
        <g
          stroke="currentColor"
          strokeLinecap="round"
          strokeLinejoin="round"
          strokeWidth="1.7"
        >
          {artwork}
        </g>
      )}
    </svg>
  );
}
